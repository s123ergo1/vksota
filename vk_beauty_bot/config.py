"""Модуль загрузки конфигурации из переменных окружения.

Загружает токен сообщества ВКонтакте и опциональный ID менеджера
из файла .env с помощью библиотеки python-dotenv.
"""

import os

from dotenv import load_dotenv

# Загружаем переменные окружения из файла .env (если он существует)
load_dotenv()

# Токен доступа сообщества ВКонтакте (обязателен для работы бота)
VK_TOKEN: str | None = os.getenv("VK_TOKEN")

# ID чата или пользователя менеджера для пересылки запросов (опционально)
MANAGER_CHAT_ID: str = os.getenv("MANAGER_CHAT_ID", "")
